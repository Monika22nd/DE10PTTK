CREATE TABLE IF NOT EXISTS tblUser6 (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fullName VARCHAR(120) NOT NULL,
  dateOfBirth DATE NOT NULL,
  address VARCHAR(255) NOT NULL,
  phoneNumber VARCHAR(20) NOT NULL UNIQUE,
  email VARCHAR(254) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS tblCustomer6 (
  userId BIGINT PRIMARY KEY REFERENCES tblUser6(id),
  customerCode VARCHAR(30) NOT NULL UNIQUE,
  memberStatus VARCHAR(20) NOT NULL,
  registeredDate DATE NOT NULL
);
CREATE TABLE IF NOT EXISTS tblAccount6 (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  userId BIGINT NOT NULL UNIQUE REFERENCES tblUser6(id),
  username VARCHAR(50) NOT NULL UNIQUE,
  passwordHash VARCHAR(255) NOT NULL,
  role VARCHAR(30) NOT NULL,
  status VARCHAR(20) NOT NULL,
  createdDate TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS tblEmployee6 (
  userId BIGINT PRIMARY KEY REFERENCES tblUser6(id),
  employeeCode VARCHAR(30) NOT NULL UNIQUE,
  position VARCHAR(80) NOT NULL,
  staffType VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS tblItemCategory6 (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  categoryCode VARCHAR(30) NOT NULL UNIQUE,
  categoryName VARCHAR(120) NOT NULL,
  description VARCHAR(500)
);
CREATE TABLE IF NOT EXISTS tblItem6 (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  categoryId BIGINT NOT NULL REFERENCES tblItemCategory6(id),
  itemCode VARCHAR(30) NOT NULL UNIQUE,
  itemName VARCHAR(150) NOT NULL,
  unit VARCHAR(30) NOT NULL,
  purchasePrice DECIMAL(15,2) NOT NULL,
  sellingPrice DECIMAL(15,2) NOT NULL,
  status VARCHAR(20) NOT NULL,
  description VARCHAR(500)
);
CREATE TABLE IF NOT EXISTS tblTransaction6 (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transactionCode VARCHAR(30) NOT NULL UNIQUE,
  transactionDate TIMESTAMP NOT NULL,
  transactionType VARCHAR(20) NOT NULL,
  status VARCHAR(20) NOT NULL
);
CREATE TABLE IF NOT EXISTS tblTransactionDetail6 (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transactionId BIGINT NOT NULL REFERENCES tblTransaction6(id),
  itemId BIGINT NOT NULL REFERENCES tblItem6(id),
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  unitPrice DECIMAL(15,2) NOT NULL CHECK (unitPrice >= 0)
);
CREATE INDEX IF NOT EXISTS idx_transaction_date6 ON tblTransaction6(transactionDate, status, transactionType);
CREATE INDEX IF NOT EXISTS idx_detail_item6 ON tblTransactionDetail6(itemId, transactionId);
